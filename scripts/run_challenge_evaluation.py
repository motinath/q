    # Master Dossier Export
    # --------------------------------------------------------------------------
    master_dossier = {
        "evaluation_timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "openqkd_real_field_validation": field_results,
        "challenge_dataset": {
            "path": dataset_path,
            "sha256": ep_sha,
            "total_records": len(df),
            "total_runs": df["run_id"].nunique(),
        },
        "rca_metrics": rca_metrics,
        "predictive_maintenance_benchmark": q_eval,
        "closed_loop_optimization": opt_results,
    }

    out_json = os.path.join(REPO_ROOT, "reports", "challenge_submission_evaluation.json")
    with open(out_json, "w") as f:
        json.dump(master_dossier, f, indent=2)

