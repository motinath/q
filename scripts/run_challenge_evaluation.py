    print("MASTER CHALLENGE EVALUATION: ALL 4 PILLARS VERIFIED [100% READY]")
    print(f"Master Evidence Dossier: file:///{out_json.replace(os.sep, '/')}")
    print(f"Optimization Markdown:   file:///{os.path.join(REPO_ROOT, 'reports', 'optimization_benchmark_results.md').replace(os.sep, '/')}")
    print("=" * 82)


